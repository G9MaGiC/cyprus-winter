#!/usr/bin/env node
/**
 * Regenerates src/lib/route-ids.generated.ts — the dependency-free id sets the
 * middleware uses to give invalid dynamic slugs a real 404 (AUD-65/113).
 *
 * Sources mirror each dynamic page's generateStaticParams exactly. The module
 * is checked in (the middleware bundle must not import the data layer);
 * route-ids.test.ts fails when the data moves until this is re-run.
 *
 * Usage: npm run generate:route-ids
 */
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

// Import the TS data modules through tsx in a child process so this script
// stays a plain .mjs like the rest of scripts/.
const dump = execFileSync(
  "npx",
  [
    "tsx",
    "-e",
    `
import { allDiscoverIds } from "./src/data/index";
import { trails } from "./src/data/trails";
import { TRAIL_LEGACY_IDS } from "./src/lib/trail-resolve";
import { wineries } from "./src/data/wineries";
import { guides } from "./src/data/guides";
import { WINE_ROUTES } from "./src/data/wine-routes";
import { REGION_CONFIGS } from "./src/data/regions";
import { MONTH_SLUGS } from "./src/lib/weather-month-suggestions";
import { routing } from "./src/i18n/routing";
console.log(JSON.stringify({
  discover: allDiscoverIds,
  // Trails accept slug aliases and legacy ids too — the [id] layout SSGs both
  // forms and the page 308-redirects aliases to the canonical id URL.
  trails: [...new Set([
    ...trails.map((t) => t.id),
    ...trails.map((t) => t.slug).filter(Boolean),
    ...Object.keys(TRAIL_LEGACY_IDS),
  ])],
  bookWinery: wineries.map((w) => w.id),
  bookGuide: guides.map((g) => g.id),
  wineRoutes: WINE_ROUTES.map((r) => r.slug),
  regions: REGION_CONFIGS.map((c) => c.slug),
  weather: MONTH_SLUGS,
  locales: routing.locales,
}));
`,
  ],
  { cwd: ROOT, maxBuffer: 1e8, encoding: "utf8" }
);
const sets = JSON.parse(dump.trim().split("\n").pop());

for (const [name, ids] of Object.entries(sets)) {
  if (!Array.isArray(ids) || ids.length === 0) throw new Error(`empty set: ${name}`);
  for (const id of ids) {
    if (typeof id !== "string" || !id) throw new Error(`bad id in ${name}: ${id}`);
  }
}

const body = `// AUTO-GENERATED by scripts/generate-route-ids.mjs — do not edit by hand.
// Dependency-free valid-slug sets for the 404 middleware (AUD-65/113); the
// sources mirror each dynamic page's generateStaticParams. route-ids.test.ts
// fails when the data layer moves until \`npm run generate:route-ids\` is
// re-run.

export const ROUTE_ID_SETS: Record<string, ReadonlySet<string>> = {
${["discover", "trails", "bookWinery", "bookGuide", "wineRoutes", "regions", "weather"]
  .map((k) => `  ${k}: new Set(${JSON.stringify(sets[k])}),`)
  .join("\n")}
};

export const LOCALES: ReadonlySet<string> = new Set(${JSON.stringify(sets.locales)});
`;

const { writeFileSync } = await import("node:fs");
writeFileSync(join(ROOT, "src/lib/route-ids.generated.ts"), body);
console.log(
  "route-ids.generated.ts written:",
  Object.entries(sets)
    .map(([k, v]) => `${k}=${v.length}`)
    .join(" ")
);
